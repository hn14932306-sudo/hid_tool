def normalize_params(values: Optional[Mapping[str, object]] = None) -> Dict[str, int]:
    result = dict(DEFAULT_PARAMS)
    if values:
        for key in result:
            if key in values:
                result[key] = int(values[key])
    return result


def decode_hover_payload(payload: bytes, strict: bool = True) -> Optional[HoverPalmSample]:
    if not isinstance(payload, (bytes, bytearray)) or len(payload) < PAYLOAD_SIZE:
        return None
    raw = bytes(payload[:PAYLOAD_SIZE])
    version = raw[0] >> 4
    if version != PAYLOAD_VERSION:
        return None
    area, area50, area20, area10 = raw[2:6]
    if strict and (
        raw[1] == 0 or area == 0
        or not (area50 <= area20 <= area10 <= area)
    ):
        return None
    return HoverPalmSample(
        version, raw[0] & 0x0F, raw[1], area, area50, area20, area10,
        int.from_bytes(raw[6:8], "little", signed=True),
        raw[8], raw[9], raw[10], raw[11] & 0x0F, raw[11] >> 4, raw,
    )


def extract_hover_report(data: bytes, fields=(), cached_offset=None):
    """Locate and decode the tune payload in a complete HID input report."""
    if not isinstance(data, (bytes, bytearray)) or len(data) < 13:
        return None
    report_id, payload = data[0], bytes(data[1:])
    if cached_offset is not None and cached_offset + PAYLOAD_SIZE <= len(payload):
        sample = decode_hover_payload(
            payload[cached_offset:cached_offset + PAYLOAD_SIZE], strict=False
        )
        if sample:
            return sample, "descriptor", cached_offset
    for field in fields:
        if (
            getattr(field, "report_type", None) == "Input"
            and getattr(field, "report_id", None) == report_id
            and getattr(field, "bit_size", None) == 96
            and getattr(field, "bit_offset", 1) % 8 == 0
            and any(usage == 0xC5 for usage in getattr(field, "usages", ()))
        ):
            offset = field.bit_offset // 8
            if offset + PAYLOAD_SIZE <= len(payload):
                sample = decode_hover_payload(
                    payload[offset:offset + PAYLOAD_SIZE], strict=False
                )
                if sample:
                    return sample, "descriptor", offset
    return None


MAIN_FLAG_KEYS = (
    "base_area20_pct", "base_area10_pct", "low_peak_max", "low_area10_pct",
    "high_peak_min", "high_peak_max", "high_thumb_max", "high_area_min",
    "high_area20_pct", "high_area10_pct", "hover_area_min",
    "finger_thumb_max", "strong_thumb_min", "strong_peak_min",
)


def evaluate_labeled_sequences(sequences, params=None):
    """Evaluate recorded labelled sequences and report data volume."""
    p = normalize_params(params)
    evaluator = HoverPalmEvaluator(p)
    expected = {"Finger": 0, "Hover": 3, "Thumb": 2}
    total = correct = 0
    confusion = {}
    class_counts = {name: 0 for name in expected}
    class_frames = {name: 0 for name in expected}
    for index, (label, samples) in enumerate(sequences):
        label = str(label).strip().title()
        if label not in expected:
            continue
        samples = list(samples)
        decision = None
        for sample in samples:
            result = evaluator.process(sample, "eval-{}".format(index))
            if sample.touch_count == p["decision_frame"]:
                decision = result.calculated_vote
        if decision is None:
            continue
        total += 1
        class_counts[label] += 1
        class_frames[label] += len(samples)
        if decision == expected[label]:
            correct += 1
        else:
            key = "{}->{}".format(label, decision)
            confusion[key] = confusion.get(key, 0) + 1
    return {"total": total, "correct": correct,
            "accuracy": correct / total if total else 0.0,
            "confusion": confusion, "class_counts": class_counts,
            "class_frames": class_frames}


def optimize_main_params(sequences, base_params=None, progress=None):
    """Fit the screenshot's main Hover/Finger/Thumb thresholds to labels.

    sequences is an iterable of (label, samples), where label is Finger, Hover,
    or Thumb and samples contains one complete Touch# 1..6 sequence.
    """
    params = normalize_params(base_params)
    labeled = [
        (str(label).strip().title(), list(samples))
        for label, samples in sequences
        if str(label).strip().title() in ("Finger", "Hover", "Thumb")
    ]
    labeled = [
        item for item in labeled
        if any(sample.touch_count == params["decision_frame"] for sample in item[1])
    ]
    if not labeled:
        return params, {"total": 0, "correct": 0, "accuracy": 0.0, "confusion": {}}

    def metric_values(key):
        values = []
        for _label, samples in labeled:
            for sample in samples:
                if key == "base_area20_pct":
                    value = sample.area20 * 100 // sample.area if sample.area else 0
                elif key in ("base_area10_pct", "low_area10_pct", "high_area10_pct"):
                    value = sample.area10 * 100 // sample.area if sample.area else 0
                elif key == "high_area20_pct":
                    value = sample.area20 * 100 // sample.area if sample.area else 0
                elif key in ("low_peak_max", "high_peak_min", "high_peak_max", "strong_peak_min"):
                    value = sample.peak_diff
                elif key in ("high_thumb_max", "finger_thumb_max", "strong_thumb_min"):
                    value = calculate_thumb_score(sample, params)[0]
                elif key in ("high_area_min", "hover_area_min"):
                    value = sample.area
                else:
                    continue
                values.extend((value - 1, value, value + 1))
        values.append(params[key])
        if key.endswith("_pct"):
            values.extend((0, 100))
        elif key.endswith("_min") or key.endswith("_max"):
            values.extend((0, 255))
        result = sorted(set(max(-32768, min(32767, int(value))) for value in values))
        return result

    candidates = {key: metric_values(key) for key in MAIN_FLAG_KEYS}
    total_steps = 1 + 3 * sum(len(candidates[key]) for key in MAIN_FLAG_KEYS)
    progress_done = 0
    if progress:
        progress(progress_done, total_steps)

    def grade(candidate):
        evaluator = HoverPalmEvaluator(candidate)
        correct = 0
        total = 0
        confusion = {}
        for index, (label, samples) in enumerate(labeled):
            actual = 0
            for sample in samples:
                result = evaluator.process(sample, "fit-{}".format(index))
                if sample.touch_count == candidate["decision_frame"]:
                    actual = result.calculated_vote
            expected = {"Finger": 0, "Hover": 3, "Thumb": 2}[label]
            total += 1
            if actual == expected:
                correct += 1
            else:
                key = "{}->{}".format(label, actual)
                confusion[key] = confusion.get(key, 0) + 1
        distance = sum(
            abs(candidate[key] - params[key]) / max(1, abs(params[key]))
            for key in MAIN_FLAG_KEYS
        )
        return correct, -distance, total, confusion

    best = dict(params)
    best_grade = grade(best)
    progress_done += 1
    if progress:
        progress(progress_done, total_steps)
    for _ in range(3):
        improved = False
        for key in MAIN_FLAG_KEYS:
            local_best = best
            local_grade = best_grade
            for value in candidates[key]:
                trial = dict(best)
                trial[key] = value
                if trial["high_peak_min"] > trial["high_peak_max"]:
                    progress_done += 1
                    if progress:
                        progress(progress_done, total_steps)
                    continue
                trial_grade = grade(trial)
                progress_done += 1
                if progress:
                    progress(progress_done, total_steps)
                if trial_grade[:2] > local_grade[:2]:
                    local_best, local_grade = trial, trial_grade
            if local_best is not best:
                best, best_grade = local_best, local_grade
                improved = True
        if not improved:
            break

    correct, _distance, total, confusion = best_grade
    before = evaluate_labeled_sequences(labeled, params)
    after = {
        "total": total, "correct": correct,
        "accuracy": correct / total if total else 0.0,
        "confusion": confusion,
        "class_counts": dict(before["class_counts"]),
        "class_frames": dict(before["class_frames"]),
    }
    return best, {**after, "before": before, "after": after}


def calculate_thumb_score(
    sample: HoverPalmSample, params: Mapping[str, int]
) -> Tuple[int, int, int]:
    p = params
    max_range = max(sample.tx_range, sample.rx_range)
    if sample.confidence != p["confidence_normal"]:
        return 0xFF, 10, max_range
    if sample.tx_range and sample.rx_range:
        ratio = (
            sample.tx_range * 10 // sample.rx_range
            if sample.tx_range > sample.rx_range
            else sample.rx_range * 10 // sample.tx_range
        )
    else:
        ratio = 10
    score = 0
    if ratio >= p["ratio_high"]:
        score += p["ratio_high_score"]
    elif ratio >= p["ratio_mid"]:
        score += p["ratio_mid_score"]
    elif ratio >= p["ratio_low"]:
        score += p["ratio_low_score"]
    if max_range >= p["range_high"]:
        score += p["range_high_score"]
    elif max_range >= p["range_mid"]:
        score += p["range_mid_score"]
    if sample.fill_rate < p["fill_low"]:
        score += p["fill_low_score"]
    elif sample.fill_rate < p["fill_mid"]:
        score += p["fill_mid_score"]
    elif sample.fill_rate < p["fill_high"]:
        score += p["fill_high_score"]
    if sample.area > p["area_high"]:
        score += p["area_high_score"]
    elif sample.area > p["area_mid"]:
        score += p["area_mid_score"]
    if (
        max_range >= p["bonus_range"]
        and sample.area > p["bonus_area"]
        and sample.fill_rate < p["bonus_fill"]
    ):
        score += p["bonus_score"]
    return score & 0xFF, ratio, max_range


class HoverPalmEvaluator:
    """Stateful reproduction of FT5452 AppHoverFingerVote."""

    def __init__(self, params: Optional[Mapping[str, object]] = None):
        self.params = normalize_params(params)
        self._states: Dict[str, HoverPalmState] = {}

    def reset(self):
        self._states.clear()

    def process(self, sample: HoverPalmSample, stream: str = "") -> HoverPalmEvaluation:
        p = self.params
        key = str(stream)
        state = self._states.get(key)
        if (
            state is None or sample.touch_count == 1
            or sample.touch_count <= state.last_touch_count
        ):
            state = HoverPalmState()
            self._states[key] = state

        score, ratio, max_range = calculate_thumb_score(sample, p)
        hover_base = (
            sample.area20 * 100 >= sample.area * p["base_area20_pct"]
            and sample.area10 * 100 >= sample.area * p["base_area10_pct"]
        )
        low_peak = (
            sample.peak_diff <= p["low_peak_max"]
            and sample.area10 * 100 >= sample.area * p["low_area10_pct"]
        )
        high_peak = (
            p["high_peak_min"] <= sample.peak_diff <= p["high_peak_max"]
            and score <= p["high_thumb_max"]
            and sample.area >= p["high_area_min"]
            and sample.area20 * 100 >= sample.area * p["high_area20_pct"]
            and sample.area10 * 100 >= sample.area * p["high_area10_pct"]
        )
        hover = sample.area >= p["hover_area_min"] and (hover_base or low_peak)
        wide = hover or high_peak
        finger = score <= p["finger_thumb_max"]
        strong_thumb = (
            score >= p["strong_thumb_min"]
            and sample.peak_diff >= p["strong_peak_min"]
        )
        decision_frame = p["decision_frame"]
        if 0 < sample.touch_count <= decision_frame:
            state.area_sum += sample.area
            if sample.touch_count < decision_frame:
                state.scope_sum += score
            if (
                sample.area == 0
                or sample.area50 * 100 < sample.area * p["direct_area50_pct"]
            ):
                state.direct_flags &= ~0x01
            state.hover_count += int(hover)
            state.wide_count += int(wide)
            state.thumb_count += int(strong_thumb)

        vote = 0
        if sample.touch_count == decision_frame:
            direct = (
                state.area_sum >= p["direct_area_sum_min"]
                and state.scope_sum <= p["direct_scope_sum_max"]
                and bool(state.direct_flags & 0x01)
            )
            if direct:
                state.direct_flags |= 0x02
            else:
                state.direct_flags &= ~0x02
            if state.thumb_count >= p["thumb_votes"] or direct:
                vote = 2
            elif (
                state.hover_count >= p["hover_votes"]
                or state.wide_count >= p["wide_votes"]
            ):
                vote = 3
        else:
            direct = bool(state.direct_flags & 0x02)
        state.last_touch_count = sample.touch_count
        return HoverPalmEvaluation(
            score, ratio, max_range, hover_base, low_peak, high_peak,
            hover, wide, finger, strong_thumb, state.area_sum, state.scope_sum,
            state.hover_count, state.wide_count, state.thumb_count,
            direct, vote,
        )
