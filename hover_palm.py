def format_fw_header(values: Optional[Mapping[str, object]] = None) -> str:
    p = normalize_params(values)
    lines = [
        "#ifndef _APP_HOVER_PALM_TUNE_CONFIG_H_",
        "#define _APP_HOVER_PALM_TUNE_CONFIG_H_",
        "",
        "/* Generated by RE024 Touch Inspector / Hover Palm. */",
    ]
    for key, macro, suffix in FW_DEFINE_MAP:
        lines.append(f"#define {macro:<40} {p[key]}{suffix}")
    lines.extend(("", "#endif", ""))
    return "\n".join(lines)


